function translateLabel(label) {
  const exact = labels.get(label);
  if (exact) return exact;
  const count = countPattern.exec(label);
  if (count) return `${count[1]} ${units.get(count[2])[Number(count[1]) === 1 ? 0 : 1]}`;
  const month = /^(1[0-2]|[1-9])月$/.exec(label);
  if (month) return dates.format(new Date(Date.UTC(2000, Number(month[1]) - 1, 1)));
  const year = /^(\d{4})年$/.exec(label);
  if (year) return year[1];
  for (const [pattern, format] of summaries) {
    const match = pattern.exec(label);
    if (match) return format(match);
  }
  return label;
}

export function translateInterface(value) {
  if (!/[\u3400-\u9fff]/.test(value)) return value;
  const label = value.trim();
  const exact = translateLabel(label);
  if (exact !== label) return value.replace(label, exact);
  // Only translate complete labels in composites. An unknown record title
  // or a sentence containing one of these words stays intact.
  return value.split(/(\s+[·/—]\s+|\s+[↗›→]|^[←+＋]\s+|\s+·\s*)/).map(part => {
    const text = part.trim();
    return text ? part.replace(text, translateLabel(text)) : part;
  }).join('');
}
