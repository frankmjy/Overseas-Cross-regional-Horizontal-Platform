export function documentLifecycle(document) {
  if (['domestic','general'].includes(document.libraryScope)) return {chapter:'',path:[]};
  const explicit = document.lifecycle || {};
  if ((document.directoryId||explicit.directoryId)&&['handover','operations'].includes(explicit.chapter))return {...explicit,path:[explicit.chapter==='handover'?'接维篇':'运维篇']};
  if (explicit.chapter === 'handover' && handoverStages.some(stage => stage.step === String(explicit.stage))) return {chapter:'handover',stage:String(explicit.stage),group:'',folder:'',path:['接维篇',handoverStages.find(stage=>stage.step===String(explicit.stage)).name]};
  if (explicit.chapter === 'operations' && !explicit.category) return {chapter:'operations',category:'',path:['运维篇']};
  const code = document.classification || explicit.folder || assignments[document.id];
  if (locations.has(code)) return locations.get(code);
  if (explicit.chapter === 'operations' && operationsCategories.some(category => category.id === explicit.category)) {
    return {chapter:'operations',category:explicit.category,path:['运维篇',operationsCategories.find(category=>category.id===explicit.category).name]};
  }
  if (/新开国手册【接维篇】/.test(document.title || '')) return {chapter:'handover',stage:'',group:'',folder:'',path:['接维篇','篇章共用']};
  if (/新开国手册【运维篇】/.test(document.title || '')) return {chapter:'operations',category:'',path:['运维篇','篇章共用']};
  return {chapter:'',path:[]};
}
export function lifecycleDocuments(documents,{chapter='',stage='',group='',folder=''}={}) {
  return documents.filter(document => {
    const location = documentLifecycle(document);
    return (!chapter || location.chapter === chapter) && (stage === '' || location.stage === String(stage)) &&
      (!group || (chapter === 'operations' ? location.category === group : location.group === group)) && (!folder || location.folder === folder);
  });
}
